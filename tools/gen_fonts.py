#!/usr/bin/env python3
"""Generate src/generated/fonts.inc and font_families.h from the fonts in third_party/fonts.

Each font is embedded byte for byte; src/fonts.cpp hands the bytes to Windows, which loads them for this process only.
font_families.h names each family once, for the code that asks GDI for a bundled font.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_icons import c_bytes  # noqa: E402

# The fonts in the order the font dropdown offers them: the family GDI matches on, the name of its constants (k<name>
# for the family, kFont<name> for the bytes), and the file.
FONTS = [
    ('Montserrat SemiBold', 'MontserratSemiBold', 'Montserrat-SemiBold.ttf'),
    ('Marcellus SC', 'MarcellusSC', 'MarcellusSC-Regular.ttf'),
    ('Cinzel', 'Cinzel', 'Cinzel-Regular.ttf'),
    ('Cormorant SC', 'CormorantSC', 'CormorantSC-SemiBold.ttf'),
    ('Barlow Condensed', 'BarlowCondensed', 'BarlowCondensed-Bold.ttf'),
]


class FontError(ValueError):
    pass


def generate(fonts: pathlib.Path) -> str:
    parts = ['// Generated by tools/gen_fonts.py from third_party/fonts. Do not edit.']
    for _, name, filename in FONTS:
        path = fonts / filename
        if not path.is_file():
            raise FontError(f'missing font {path}')
        parts.append(c_bytes(f'kFont{name}', path.read_bytes()))
    rows = ', '.join(f'{{k{name}, kFont{name}, sizeof(kFont{name})}}' for _, name, _ in FONTS)
    parts.append(f'const BundledFont kBundledFonts[] = {{{rows}}};')
    return '\n'.join(parts) + '\n'


def generate_families() -> str:
    lines = ['// Generated by tools/gen_fonts.py. Do not edit.', '#pragma once', '', 'namespace headsup', '{',
             "    // The bundled fonts' families: the names GDI matches on once their bytes are loaded."]
    lines += [f'    constexpr const char* k{name} = "{family}";' for family, name, _ in FONTS]
    lines += ['}', '']
    return '\n'.join(lines)


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    out = root / 'src' / 'generated' / 'fonts.inc'
    try:
        text = generate(root / 'third_party' / 'fonts')
    except FontError as error:
        print(f'gen_fonts: {error}', file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    (out.parent / 'font_families.h').write_text(generate_families(), encoding='utf-8')
    print(f'fonts: {len(FONTS)} bundled -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
