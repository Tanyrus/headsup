#!/usr/bin/env python3
"""Generate src/generated/zones.inc from data/phoenix_zones.tsv and data/phoenix_weather.tsv.

With --check DIR, check DIR's two files by the same rules and write nothing: refresh.sh does, before it copies a
Phoenix refresh's zone files into data/.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_mobdata import c_string  # noqa: E402

WEATHER_DAYS = 2160
LAST_REGION = 45
UNKNOWN_REGION = 255
NO_CALENDAR = 255
DAY_KINDS = 256  # a calendar's day is a byte, an index into the distinct days
ZONES_HEADER = 'id\tname\tregion\tcalendar'
WEATHER_HEADER = 'calendar\tdays'


class DataError(ValueError):
    pass


def parse_zones(text: str) -> list:
    lines = text.splitlines()
    if not lines or lines[0] != ZONES_HEADER:
        raise DataError('phoenix_zones.tsv: the header must be ' + ZONES_HEADER.replace('\t', ', '))
    zones, seen = [], set()
    for number, line in enumerate(lines[1:], start=2):
        fields = line.split('\t')
        if (len(fields) != 4 or not fields[0].isdigit() or not fields[2].isdigit()
                or not (fields[3] == '' or fields[3].isdigit())):
            raise DataError(f'phoenix_zones.tsv line {number}: id, name, region and calendar, the numbers whole')
        zone, region = int(fields[0]), int(fields[2])
        if zone in seen:
            raise DataError(f'phoenix_zones.tsv line {number}: zone {zone} again')
        if region > LAST_REGION and region != UNKNOWN_REGION:
            raise DataError(f'phoenix_zones.tsv line {number}: region {region} is not one of Phoenix\'s')
        seen.add(zone)
        zones.append({'id': zone, 'name': fields[1], 'region': region,
                      'calendar': int(fields[3]) if fields[3] else NO_CALENDAR})
    return sorted(zones, key=lambda z: z['id'])


def parse_calendars(text: str) -> list:
    lines = text.splitlines()
    if not lines or lines[0] != WEATHER_HEADER:
        raise DataError('phoenix_weather.tsv: the header must be ' + WEATHER_HEADER.replace('\t', ', '))
    calendars = []
    for number, line in enumerate(lines[1:], start=2):
        fields = line.split('\t')
        if (len(fields) != 2 or fields[0] != str(len(calendars))
                or not re.fullmatch(r'[0-9A-F]{%d}' % (WEATHER_DAYS * 4), fields[1])):
            raise DataError(f'phoenix_weather.tsv line {number}: calendar {len(calendars)} and '
                            f'{WEATHER_DAYS} days of hex')
        days = fields[1]
        calendars.append([int(days[i + 2:i + 4] + days[i:i + 2], 16) for i in range(0, len(days), 4)])
    return calendars


def filled(days: list, calendar: int) -> list:
    """Each blank day (0) as the day before it, which is how Phoenix's entryForDay reads a calendar."""
    if days[0] == 0:
        raise DataError(f'weather calendar {calendar} has no weather on its first day')
    out = []
    for day in days:
        out.append(day or out[-1])
    return out


def generate(zones: list, calendars: list) -> str:
    if len(calendars) >= NO_CALENDAR:
        raise DataError(f'{len(calendars)} weather calendars do not fit a byte')
    for index, zone in enumerate(zones):
        if zone['id'] != index:
            raise DataError(f'zone {index} is missing: the plugin finds a zone at its id in the table')
        if zone['calendar'] != NO_CALENDAR and zone['calendar'] >= len(calendars):
            raise DataError(f'zone {zone["id"]} names weather calendar {zone["calendar"]}, past the last')
    calendars = [filled(days, number) for number, days in enumerate(calendars)]
    kinds = sorted({day for days in calendars for day in days})
    if len(kinds) > DAY_KINDS:
        raise DataError(f'{len(kinds)} distinct weather days do not fit a byte')
    kind = {day: index for index, day in enumerate(kinds)}
    lines = ['// Generated by tools/gen_zones.py from data/phoenix_zones.tsv and data/phoenix_weather.tsv.',
             '// Do not edit.',
             f'static_assert(kWeatherDays == {WEATHER_DAYS}, "gen_zones.py writes {WEATHER_DAYS} days a calendar");',
             f'static_assert(kUnknownRegion == {UNKNOWN_REGION}, "gen_zones.py writes {UNKNOWN_REGION} for none");',
             f'static_assert(kNoCalendar == {NO_CALENDAR}, "gen_zones.py writes {NO_CALENDAR} for none");',
             f'constexpr size_t kRegionCount = {LAST_REGION + 1};', 'const ZoneRecord kZones[] = {']
    lines += [f'    {{{c_string(z["name"])}, {z["region"]}, {z["calendar"]}}},' for z in zones]
    lines += ['};', 'const uint16_t kWeatherOdds[] = {']
    lines += ['    ' + ' '.join(f'0x{v:04x},' for v in kinds[start:start + 16]) for start in range(0, len(kinds), 16)]
    lines += ['};', 'const uint8_t kWeatherCalendars[][kWeatherDays] = {']
    for days in calendars:
        lines.append('    {')
        for start in range(0, len(days), 24):
            lines.append('        ' + ' '.join(f'{kind[v]},' for v in days[start:start + 24]))
        lines.append('    },')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv) -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    check = argv[1:2] == ['--check']
    if len(argv) != (3 if check else 1):
        print('usage: gen_zones.py [--check DATA_DIR]', file=sys.stderr)
        return 2
    data = pathlib.Path(argv[2]) if check else root / 'data'
    try:
        zones = parse_zones((data / 'phoenix_zones.tsv').read_text(encoding='utf-8'))
        calendars = parse_calendars((data / 'phoenix_weather.tsv').read_text(encoding='utf-8'))
        text = generate(zones, calendars)
    except (OSError, DataError) as error:
        print(f'gen_zones: {error}', file=sys.stderr)
        return 1
    if check:
        print(f'zones: {len(zones)} zones, {len(calendars)} weather calendars in {data} pass')
        return 0
    out = root / 'src' / 'generated' / 'zones.inc'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(f'zones: {len(zones)} zones, {len(calendars)} weather calendars -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
