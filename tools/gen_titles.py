#!/usr/bin/env python3
"""Generate src/generated/titles.inc from data/phoenix_titles.tsv, in id order for the plugin's binary search."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_mobdata import c_string  # noqa: E402

HEADER = 'id\tname'


class DataError(ValueError):
    pass


def parse_titles(text: str) -> list:
    lines = text.splitlines()
    if not lines or lines[0] != HEADER:
        raise DataError('phoenix_titles.tsv: the header must be ' + HEADER.replace('\t', ', '))
    titles = []
    for number, line in enumerate(lines[1:], start=2):
        fields = line.split('\t')
        if len(fields) != 2 or not fields[0].isdigit() or not fields[1]:
            raise DataError(f'phoenix_titles.tsv line {number}: an id and a name')
        title = int(fields[0])
        if titles and title <= titles[-1][0]:
            raise DataError(f'phoenix_titles.tsv line {number}: title {title} after {titles[-1][0]}, out of order')
        titles.append((title, fields[1]))
    return titles


def generate(titles: list) -> str:
    lines = ['// Generated by tools/gen_titles.py from data/phoenix_titles.tsv. Do not edit.']
    lines += [f'    {{{title}, {c_string(name)}}},' for title, name in titles]
    return '\n'.join(lines) + '\n'


def main(argv) -> int:
    if len(argv) != 1:
        print('usage: gen_titles.py', file=sys.stderr)
        return 2
    root = pathlib.Path(__file__).resolve().parent.parent
    try:
        titles = parse_titles((root / 'data' / 'phoenix_titles.tsv').read_text(encoding='utf-8'))
    except (OSError, DataError) as error:
        print(f'gen_titles: {error}', file=sys.stderr)
        return 1
    out = root / 'src' / 'generated' / 'titles.inc'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate(titles), encoding='utf-8')
    print(f'titles: {len(titles)} titles -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
